export function themeToCssVars(dark: boolean): React.CSSProperties {
  const tokens = dark ? THEMES.dark : THEMES.light;
  // React's CSSProperties type doesn't enumerate custom properties -- this
  // cast is the standard, harmless way to hand it an object keyed by --xxx.
  return tokens as React.CSSProperties;
}
